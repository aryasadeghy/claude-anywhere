// Claude in Chrome (lib/chrome.mjs): what is detected on a computer, what Connect writes, when a run
// gets `--chrome`, and how the transcript words the extension's tools. Nothing here touches the real
// browser, registry or Claude folder: CA_CHROME_HOME stands a whole machine in (a folder with its own
// AppData, .claude and a registry.json), and the run is a stand-in Claude Code that only records its arguments.
import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ca-chrome-test-'));
process.env.CLAUDE_ANYWHERE_DATA_DIR = path.join(tmp, 'data');
delete process.env.CLAUDE_CONFIG_DIR;

const chrome = await import('../lib/chrome.mjs');
const claudeCode = await import('../lib/claude-code.mjs');
const { appPrompt } = await import('../lib/app-prompt.mjs');
// The page's own file, loaded the way the page loads it: as a script that sets window.chromeLabel.
const win = {}; new Function('window', fs.readFileSync(new URL('../public/chrome-labels.js', import.meta.url), 'utf8'))(win);
const { chromeLabel } = win;

let n = 0;
// A fresh machine of the given kind, with Chrome's profile folders and, optionally, the extension in one.
function machine(platform, { browser = true, extension = false, profile = 'Default' } = {}) {
  const home = path.join(tmp, 'm' + ++n);
  fs.mkdirSync(home, { recursive: true });
  process.env.CA_CHROME_HOME = home;
  process.env.CA_CHROME_PLATFORM = platform;
  const data = platform === 'win32' ? path.join(home, 'AppData', 'Local', 'Google', 'Chrome', 'User Data') : platform === 'darwin' ? path.join(home, 'Library', 'Application Support', 'Google', 'Chrome') : path.join(home, '.config', 'google-chrome');
  if (browser) fs.mkdirSync(path.join(data, 'Default'), { recursive: true });
  if (extension) fs.mkdirSync(path.join(data, profile, 'Extensions', chrome.EXTENSION_ID, '1.0_0'), { recursive: true });
  return { home, data };
}
const chromeOf = (s) => s.browsers.find((b) => b.id === 'chrome');

test('a computer with no Chrome says so, and Connect refuses', async () => {
  machine('win32', { browser: false });
  const s = await chrome.status();
  assert.equal(s.state, 'no-browser');
  assert.equal(chromeOf(s).found, false);
  await assert.rejects(chrome.connect(), /Chrome is not installed/);
});

test('the extension is found in any profile folder, and only there', async () => {
  machine('win32');
  assert.equal((await chrome.status()).state, 'no-extension');
  machine('win32', { extension: true, profile: 'Profile 2' });
  const s = await chrome.status();
  assert.equal(chromeOf(s).extension, true);
  assert.deepEqual(chromeOf(s).profiles, ['Profile 2']);
  assert.equal(s.state, 'no-host');
  // A folder that is not a profile does not count.
  const { data } = machine('win32');
  fs.mkdirSync(path.join(data, 'System Profile', 'Extensions', chrome.EXTENSION_ID), { recursive: true });
  assert.equal((await chrome.status()).extension, false);
});

test('Windows: Connect writes the wrapper, the manifest and the registry key the CLI writes, and the card turns ready', async () => {
  const { home } = machine('win32', { extension: true });
  const s = await chrome.connect();
  assert.equal(s.state, 'ready');
  const wrapper = path.join(home, '.claude', 'chrome', 'chrome-native-host.bat');
  const manifest = path.join(home, 'AppData', 'Roaming', 'Claude Code', 'ChromeNativeHost', 'com.anthropic.claude_code_browser_extension.json');
  const bin = chrome.binary();
  assert.equal(fs.readFileSync(wrapper, 'utf8'), `@echo off\nREM Chrome native host wrapper script\nREM Generated by Claude Code - do not edit manually\n"${bin}" "--chrome-native-host"\n`);
  assert.deepEqual(JSON.parse(fs.readFileSync(manifest, 'utf8')), { name: chrome.HOST_NAME, description: 'Claude Code Browser Extension Native Host', path: wrapper, type: 'stdio', allowed_origins: ['chrome-extension://fcoeoabgfenejglbffodgkkbkcdhcgfn/'] });
  const reg = JSON.parse(fs.readFileSync(path.join(home, 'registry.json'), 'utf8'));
  assert.equal(reg['HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts\\com.anthropic.claude_code_browser_extension'], manifest);
  assert.equal(chromeOf(s).target, bin);
  // Again changes nothing.
  assert.equal((await chrome.connect()).state, 'ready');
});

test('a host that points at a Claude Code that is gone is stale, and Connect repairs it', async () => {
  const { home } = machine('win32', { extension: true });
  await chrome.connect();
  const wrapper = path.join(home, '.claude', 'chrome', 'chrome-native-host.bat');
  fs.writeFileSync(wrapper, '@echo off\nREM Generated by Claude Code - do not edit manually\n"C:\\gone\\claude.exe" "--chrome-native-host"\n');
  const s = await chrome.status();
  assert.equal(s.state, 'stale');
  assert.equal(chromeOf(s).target, 'C:\\gone\\claude.exe');
  assert.equal(chromeOf(s).targetExists, false);
  assert.equal((await chrome.connect()).state, 'ready');
});

test('a registry key whose manifest was deleted is not a host', async () => {
  const { home } = machine('win32', { extension: true });
  await chrome.connect();
  fs.rmSync(path.join(home, 'AppData', 'Roaming', 'Claude Code'), { recursive: true });
  const s = await chrome.status();
  assert.equal(chromeOf(s).registered, false);
  assert.equal(s.state, 'no-host');
});

test('macOS and Linux: the manifest sits in the browser\'s own NativeMessagingHosts folder, the wrapper is executable', async () => {
  for (const platform of ['darwin', 'linux']) {
    const { home, data } = machine(platform, { extension: true });
    assert.equal((await chrome.status()).state, 'no-host');
    const s = await chrome.connect();
    assert.equal(s.state, 'ready', platform);
    const mf = path.join(data, 'NativeMessagingHosts', chrome.HOST_NAME + '.json');
    const wrapper = path.join(home, '.claude', 'chrome', 'chrome-native-host');
    assert.equal(JSON.parse(fs.readFileSync(mf, 'utf8')).path, wrapper);
    assert.match(fs.readFileSync(wrapper, 'utf8'), /^#!\/bin\/sh\n# Chrome native host wrapper script\n# Generated by Claude Code - do not edit manually\nexec /);
    if (process.platform !== 'win32') assert.ok(fs.statSync(wrapper).mode & 0o100);
    assert.equal(fs.existsSync(path.join(home, 'registry.json')), false, 'no registry off Windows');
  }
});

test('the labels: a page opened, a screenshot, a page read', () => {
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__navigate', { url: 'https://mail.example.com/inbox?x=1', tabId: 3 }), ['Opened', 'mail.example.com']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__navigate', { url: 'example.org/a' }), ['Opened', 'example.org']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__navigate', { url: 'back' }), ['Went back in Chrome', '']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__computer', { action: 'screenshot' }), ['Took a screenshot of the page', '']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__computer', { action: 'left_click', coordinate: [1, 2] }), ['Clicked in Chrome', '']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__read_page', {}), ['Read the page', '']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__get_page_text', {}), ['Read the page', '']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__find', { query: 'the login button' }), ['Looked for', 'the login button']);
  assert.deepEqual(chromeLabel('mcp__claude-in-chrome__something_new', {}), ['Used Chrome', 'something new']);
  assert.equal(chromeLabel('mcp__claude-anywhere__preview_navigate', {}), null);
  assert.equal(chromeLabel('Bash', {}), null);
});

test('the prompt mentions Chrome only when it is on, and names no app tool that is not registered', async () => {
  const on = appPrompt({ cwd: tmp, tools: ['preview_start'], chrome: true });
  assert.match(on, /mcp__claude-in-chrome__\*/);
  assert.match(on, /Browser pane/);
  assert.doesNotMatch(appPrompt({ cwd: tmp, tools: ['preview_start'] }), /claude-in-chrome/);
});

// A stand-in Claude Code: Claude Code takes a script as well as a binary, so this one writes down how it
// was started and ends. Settings › Claude Code points every run at it the way it points at a download.
test('a run is started with --chrome only when Chrome is on for its session', async () => {
  const dir = path.join(tmp, 'data', 'claude-code'); fs.mkdirSync(dir, { recursive: true });
  const out = path.join(tmp, 'argv.jsonl');
  const fake = path.join(dir, '999.0.0', 'claude.mjs'); fs.mkdirSync(path.dirname(fake), { recursive: true });
  fs.writeFileSync(fake, `import fs from 'node:fs'; fs.appendFileSync(${JSON.stringify(out)}, JSON.stringify(process.argv.slice(2)) + '\\n'); process.exit(0);\n`);
  fs.writeFileSync(path.join(dir, 'current.json'), JSON.stringify({ version: '999.0.0', sdk: '999.0.0', file: fake, at: Date.now() }));
  claudeCode.useDir(dir);
  assert.equal(claudeCode.spawnOptions().pathToClaudeCodeExecutable, fake);
  const { startRun } = await import('../lib/runs.mjs');
  const started = [];
  // A run that was started keeps timers of its own (the ten minutes it rests for); the file ends when its tests have.
  after(() => { for (const r of started) { try { r.close(); } catch {} } setTimeout(() => process.exit(0), 300).unref(); });
  const on = new Set(['with']);
  chrome.setPolicy((id) => on.has(id));
  const argvFor = async (id) => {
    fs.rmSync(out, { force: true });
    started.push(startRun({ newId: id, cwd: tmp, prompt: 'hi' }).run);
    for (let i = 0; i < 200 && !fs.existsSync(out); i++) await new Promise((r) => setTimeout(r, 50));
    return JSON.parse(fs.readFileSync(out, 'utf8').trim().split('\n')[0]);
  };
  assert.ok((await argvFor('with')).includes('--chrome'), 'on');
  assert.ok(!(await argvFor('without')).includes('--chrome'), 'off');
  assert.equal(chrome.wanted('with'), true);
  assert.equal(chrome.wanted('without'), false);
});
